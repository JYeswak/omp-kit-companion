// lifecycle-check.ts -- lifecycle manifest currency gate (fresh-gate step, CI).
//
// docs/lifecycle.json is the checked version of the idea-to-happy-product phase
// map. This gate keeps the generated docs/lifecycle.md faithful to it:
//   1. Every manifest row names a known phase exactly once, a nonempty exit
//      criterion, verbs that resolve in the COMMANDS registry (src/commands.ts,
//      imported -- never grepped), doc/test paths that exist in the tree, and a
//      turnline field name (or value_<slug>/unsaved_<slug>) or UNKNOWN.
//   2. docs/lifecycle.md renders the manifest (src/lifecycle.ts, pure); --check
//      fails on drift, otherwise the render is written.
//   3. --gap PHASE:FACET (FACET verbs|doc|test|metric) exits 1 while that row's
//      facet is still a gap (LIFECYCLE_GAP_OPEN), so a gap bead's close replays
//      a command that proves its own gap filled, not just a green manifest.
//
// Usage: bun scripts/lifecycle-check.ts [--root DIR] [--check] [--gap PHASE:FACET]
// Exit 0 GREEN, 1 RED (each finding named), 2 usage or unreadable input.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { lifecycleGaps, lifecycleManifestPath, loadLifecycleManifest, renderLifecycleDoc, validateLifecycleManifest, type LifecycleManifest } from "../src/lifecycle.ts";

const GENERATED_MARKER = "<!-- generated by `bun scripts/lifecycle-check.ts`";

function usage(message: string): never {
	console.error(`usage: bun scripts/lifecycle-check.ts [--root DIR] [--check] [--gap PHASE:FACET]\nerror: ${message}`);
	process.exit(2);
}

const GAP_FACETS: Record<string, true> = { verbs: true, doc: true, test: true, metric: true };

function parseArgv(argv: string[]): { root: string; check: boolean; gap: { phase: string; facet: string } | null } {
	let root = resolve(import.meta.dir, "..");
	let check = false;
	let gap: { phase: string; facet: string } | null = null;
	for (let index = 0; index < argv.length; index += 1) {
		const arg = argv[index] ?? "";
		if (arg === "--check") {
			check = true;
		} else if (arg === "--root") {
			const value = argv[index + 1];
			if (value === undefined || value === "") usage("--root needs a directory");
			root = resolve(value);
			index += 1;
		} else if (arg === "--gap") {
			const value = argv[index + 1] ?? "";
			const split = value.lastIndexOf(":");
			const phase = split > 0 ? value.slice(0, split) : "";
			const facet = split > 0 ? value.slice(split + 1) : "";
			if (phase === "" || GAP_FACETS[facet] !== true) usage("--gap needs PHASE:FACET with FACET verbs, doc, test or metric");
			gap = { phase, facet };
			index += 1;
		} else {
			usage(`unknown argument ${JSON.stringify(arg)}`);
		}
	}
	return { root, check, gap };
}

async function main(argv: string[]): Promise<number> {
	const { root, check, gap } = parseArgv(argv);
	const manifestPath = lifecycleManifestPath(root);
	const loaded = loadLifecycleManifest(manifestPath);
	if (loaded.reason !== "ok" || loaded.manifest === null) {
		console.error(`LIFECYCLE_MANIFEST_UNREADABLE: docs/lifecycle.json cannot be loaded (${loaded.reason})`);
		return 1;
	}
	const findings = validateLifecycleManifest(loaded.manifest, root);
	if (findings.length > 0) {
		for (const finding of findings) console.error(finding);
		return 1;
	}
	const manifest = loaded.manifest as LifecycleManifest;
	if (gap !== null) {
		if (!manifest.rows.some(row => row.phase === gap.phase)) usage(`--gap names unknown phase ${JSON.stringify(gap.phase)}`);
		if (lifecycleGaps(manifest).some(open => open.phase === gap.phase && open.facet === gap.facet)) {
			console.error(`LIFECYCLE_GAP_OPEN: phase ${gap.phase} is still missing its ${gap.facet} in docs/lifecycle.json`);
			return 1;
		}
		console.error(`LIFECYCLE_GAP_CLOSED: phase ${gap.phase} has its ${gap.facet}`);
	}
	const rendered = renderLifecycleDoc(manifest);
	const docPath = join(root, "docs", "lifecycle.md");
	if (check) {
		if (!existsSync(docPath)) {
			console.error("LIFECYCLE_DOC_ABSENT: docs/lifecycle.md does not exist; run without --check to render it");
			return 1;
		}
		const current = readFileSync(docPath, "utf8");
		if (current !== rendered) {
			console.error("LIFECYCLE_DOC_DRIFT: docs/lifecycle.md does not match docs/lifecycle.json; run without --check to render it");
			return 1;
		}
		return 0;
	}
	if (existsSync(docPath) && !readFileSync(docPath, "utf8").includes(GENERATED_MARKER)) {
		console.error("LIFECYCLE_DOC_NOT_GENERATED: docs/lifecycle.md exists and is not generated; refusing to overwrite");
		return 1;
	}
	writeFileSync(docPath, rendered);
	return 0;
}

if (import.meta.main) process.exit(await main(process.argv.slice(2)));
