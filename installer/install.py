def _load_bootstrap() -> types.ModuleType:
    """Load exact canonical bytes in memory, including under ``python3 -I -c``.

    Private module names satisfy dataclasses without trusting existing imports.
    Only kitlib_run's absolute sibling import is temporarily bound; its normal
    script-directory path insertion is discarded before returning. __file__ is
    synthetic module metadata, never a source lookup or an extracted code file.
    """
    modules = {}
    previous_pysafe = sys.modules.get("pysafe")
    previous_path = sys.path[:]
    try:
        for name in ("pysafe", "kitlib_run"):
            source = base64.b85decode(_BOOTSTRAP_SOURCES[name])
            if hashlib.sha256(source).hexdigest() != _BOOTSTRAP_SHA256[name]:
                raise ValueError("installer canonical runner payload digest mismatch: " + name)
            module = types.ModuleType("_omp_kit_installer_" + name)
            module.__file__ = os.devnull + "/" + name + ".py"
            sys.modules[module.__name__] = module
            exec(compile(source, "<installer embedded " + name + ">", "exec"), module.__dict__)
            modules[name] = module
            if name == "pysafe":
                module.__dict__["_reaper_source"] = source.decode("utf-8")
                sys.modules["pysafe"] = module
        return modules["kitlib_run"]
    finally:
        sys.path[:] = previous_path
        if previous_pysafe is None:
            sys.modules.pop("pysafe", None)
        else:
            sys.modules["pysafe"] = previous_pysafe


