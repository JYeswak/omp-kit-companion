#!/usr/bin/env python3
"""Deliver the canonical runner modules inside the standalone installer and kitlib run.

Regenerate before release: python3 -I installer/embed-bootstrap.py
Check without writing:    python3 -I installer/embed-bootstrap.py --check
List declared paths:      python3 -I installer/embed-bootstrap.py --list

This is a fixed source-transport producer, not a Python rewriter. It copies the
exact bytes of scripts/pysafe.py and scripts/kitlib_run.py into one delimited
payload; no module source is transformed or maintained in the installer. Raw
base85 (no compression timestamps/version dependencies) makes output identical
on every supported Python/platform. Like PyPA get-pip's generated embedded
payload (https://github.com/pypa/get-pip), this avoids a second implementation
of bootstrap mechanics. Unlike get-pip, the consumer loads no temporary code.

EMBEDS below is the declared map of every generated output to the inputs it is
generated from (EMBEDDEP1, ompkit-fp72.120.16.197). It stays a JSON object
whose closing brace sits alone on its line: scripts/affected-tests.ts reads it
as data, so a change to an input selects the tests of its output, and
scripts/check-staged-embed.sh refuses a commit whose staged output is stale.
Adding an output is one more row plus its renderer in RENDERERS.

src/kitlib/pysafe-source.ts holds the exact bytes of scripts/pysafe.py (base64,
with their SHA-256) that src/kitlib/run.ts hands to its parent-death reaper
(GROUPREAP1), so a compiled binary needs no scripts/ beside it. An import
attribute (`with { type: "text" }`) would embed the file too, but the regexploit
gate cannot parse one, and the default file loader emits a second output that
package-release's single-file extension bundles refuse.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BEGIN = "# BEGIN GENERATED CANONICAL RUNNER\n"
END = "# END GENERATED CANONICAL RUNNER\n"
EMBEDS = {
    "installer/install.py": ["scripts/pysafe.py", "scripts/kitlib_run.py"],
    "src/kitlib/pysafe-source.ts": ["scripts/pysafe.py"]
}


def payload(inputs: list[str]) -> str:
    lines = [BEGIN, "# Generated by installer/embed-bootstrap.py; do not edit this payload.\n",
             "_BOOTSTRAP_SOURCES = {\n"]
    digests = {}
    for path in inputs:
        name = Path(path).stem
        source = (ROOT / path).read_bytes()
        digests[name] = hashlib.sha256(source).hexdigest()
        encoded = base64.b85encode(source).decode("ascii")
        lines.append(f"    {name!r}: (\n")
        for offset in range(0, len(encoded), 100):
            lines.append(f"        {encoded[offset:offset + 100].encode('ascii')!r}\n")
        lines.append("    ),\n")
    lines.append("}\n_BOOTSTRAP_SHA256 = " + repr(digests) + "\n" + END)
    return "".join(lines)


def render_installer(current: str, inputs: list[str]) -> str:
    """Splice the delimited runner payload into the installer, refusing a malformed one."""
    if current.count(BEGIN) != 1 or current.count(END) != 1:
        raise ValueError("installer must contain exactly one canonical runner payload")
    start = current.index(BEGIN)
    end = current.index(END) + len(END)
    if end <= start:
        raise ValueError("canonical runner payload delimiters are out of order")
    return current[:start] + payload(inputs) + current[end:]


def render_pysafe_ts(current: str, inputs: list[str]) -> str:
    """Render run.ts's embedded reaper source; the output is wholly generated."""
    del current
    (path,) = inputs
    source = (ROOT / path).read_bytes()
    encoded = base64.b64encode(source).decode("ascii")
    lines = [f"// Generated by installer/embed-bootstrap.py from {path}; do not edit.\n",
             "// src/kitlib/run.ts hands these exact bytes to its parent-death reaper (GROUPREAP1).\n",
             f'export const PYSAFE_SHA256 = "{hashlib.sha256(source).hexdigest()}";\n',
             "export const PYSAFE_SOURCE_BASE64 = [\n"]
    for offset in range(0, len(encoded), 100):
        lines.append(f'\t"{encoded[offset:offset + 100]}",\n')
    lines.append('].join("");\n')
    return "".join(lines)


RENDERERS = {"installer/install.py": render_installer, "src/kitlib/pysafe-source.ts": render_pysafe_ts}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="refuse stale generated bytes without writing")
    mode.add_argument("--list", action="store_true", help="print every declared output and input path, one per line")
    args = parser.parse_args()
    if set(EMBEDS) != set(RENDERERS):
        parser.error("EMBEDS and RENDERERS must declare the same outputs")
    if args.list:
        print("\n".join(dict.fromkeys(path for output, inputs in EMBEDS.items() for path in (output, *inputs))))
        return 0
    stale = []
    for output, inputs in EMBEDS.items():
        target = ROOT / output
        current = target.read_text(encoding="utf-8")
        try:
            generated = RENDERERS[output](current, inputs)
        except ValueError as error:
            parser.error(f"{output}: {error}")
        if generated == current:
            continue
        if args.check:
            stale.append(f"{output} (from {', '.join(inputs)})")
            continue
        with target.open("w", encoding="utf-8", newline="\n") as handle:
            handle.write(generated)
    if stale:
        parser.exit(1, "installer bootstrap is stale: " + "; ".join(stale) +
                    "; run python3 -I installer/embed-bootstrap.py\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
