#!/usr/bin/env python3
"""Deliver the two canonical runner modules inside the standalone installer.

Regenerate before release: python3 -I installer/embed-bootstrap.py
Check without writing:    python3 -I installer/embed-bootstrap.py --check

This is a fixed source-transport producer, not a Python rewriter. It copies the
exact bytes of scripts/pysafe.py and scripts/kitlib_run.py into one delimited
payload; no module source is transformed or maintained in the installer. Raw
base85 (no compression timestamps/version dependencies) makes output identical
on every supported Python/platform. Like PyPA get-pip's generated embedded
payload (https://github.com/pypa/get-pip), this avoids a second implementation
of bootstrap mechanics. Unlike get-pip, the consumer loads no temporary code.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BEGIN = "# BEGIN GENERATED CANONICAL RUNNER\n"
END = "# END GENERATED CANONICAL RUNNER\n"
MODULES = ("pysafe", "kitlib_run")


def payload() -> str:
    lines = [BEGIN, "# Generated by installer/embed-bootstrap.py; do not edit this payload.\n",
             "_BOOTSTRAP_SOURCES = {\n"]
    digests = {}
    for name in MODULES:
        source = (ROOT / "scripts" / (name + ".py")).read_bytes()
        digests[name] = hashlib.sha256(source).hexdigest()
        encoded = base64.b85encode(source).decode("ascii")
        lines.append(f"    {name!r}: (\n")
        for offset in range(0, len(encoded), 100):
            lines.append(f"        {encoded[offset:offset + 100].encode('ascii')!r}\n")
        lines.append("    ),\n")
    lines.append("}\n_BOOTSTRAP_SHA256 = " + repr(digests) + "\n" + END)
    return "".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="refuse stale generated installer bytes without writing")
    args = parser.parse_args()
    installer = ROOT / "installer" / "install.py"
    source = installer.read_text(encoding="utf-8")
    if source.count(BEGIN) != 1 or source.count(END) != 1:
        parser.error("installer must contain exactly one canonical runner payload")
    start = source.index(BEGIN)
    end = source.index(END) + len(END)
    if end <= start:
        parser.error("canonical runner payload delimiters are out of order")
    generated = source[:start] + payload() + source[end:]
    if generated == source:
        return 0
    if args.check:
        parser.exit(1, "installer bootstrap is stale; run python3 -I installer/embed-bootstrap.py\n")
    with installer.open("w", encoding="utf-8", newline="\n") as output:
        output.write(generated)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
